using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Immediate.Handlers.Generators;

public sealed partial class ImmediateHandlersGenerator
{
	/// <summary>Reports each handler's behavior candidates and the same selection decisions used for generation.</summary>
	private static void RenderDebugReport(
		SourceProductionContext context,
		ImmutableArray<Handler> handlers,
		ImmutableArray<BehaviorRegistration> assemblyBehaviors
	)
	{
		var text = new StringBuilder();
		Line("<auto-generated/>");
		Line("Immediate.Handlers behavior selection");
		Line("Enabled by ImmediateHandlers_GenerateDebugFile.");

		if (handlers.IsEmpty)
			Line("No handlers found.");

		foreach (var handler in handlers.OrderBy(h => h.DisplayName, StringComparer.Ordinal))
		{
			context.CancellationToken.ThrowIfCancellationRequested();
			var response = handler.ResponseType ?? new GenericType { Name = "global::System.ValueTuple", Implements = [] };
			var effectiveBehaviors = handler.OverrideBehaviors?.AsEnumerable() ?? assemblyBehaviors.AsEnumerable();
			var aborted = effectiveBehaviors.Any(b => b.Behavior is null);

			Line("");
			Line($"Handler: {handler.DisplayName}");
			Line($"  Pipeline: {(handler.IsStreaming ? "streaming" : "regular")}");
			Line($"  Request type: {handler.RequestType.Name}");
			Line($"  Request available types: {AvailableTypes(handler.RequestType)}");
			Line($"  Response type: {response.Name}");
			Line($"  Response available types: {AvailableTypes(response)}");

			if (aborted)
				Line("  Pipeline generation aborted: an effective behavior registration is invalid.");

			if (assemblyBehaviors.IsEmpty && (handler.OverrideBehaviors is null or { Count: 0 }))
				Line("  No behaviors registered.");

			foreach (var registration in assemblyBehaviors)
				ReportBehavior(registration, "assembly", handler.OverrideBehaviors is not null);

			if (handler.OverrideBehaviors is { } overrides)
			{
				Line("  Handler-specific behaviors replace the assembly behaviors.");
				foreach (var registration in overrides)
					ReportBehavior(registration, "handler", replaced: false);
			}

			void ReportBehavior(BehaviorRegistration registration, string origin, bool replaced)
			{
				context.CancellationToken.ThrowIfCancellationRequested();
				var reasons = new List<string>();
				if (replaced)
					reasons.Add("Replaced by handler-specific behaviors.");

				if (registration.Behavior is not { } behavior)
					reasons.Add(registration.Error ?? "Invalid behavior registration.");
				else
				{
					if (behavior.IsStreaming != handler.IsStreaming)
						reasons.Add($"Pipeline kind mismatch: behavior is {(behavior.IsStreaming ? "streaming" : "regular")}, handler is {(handler.IsStreaming ? "streaming" : "regular")}.");

					CheckConstraints("Request", behavior.RequestType, handler.RequestType);
					CheckConstraints("Response", behavior.ResponseType, response);

					if (aborted && reasons.Count == 0)
						reasons.Add("Pipeline generation aborted by another invalid behavior registration.");
				}

				Line($"  [{(reasons.Count == 0 ? "USED" : "NOT USED")}] {registration.TypeName} ({origin})");
				Line($"    Declaration: {registration.Declaration}");
				if (registration.Behavior is { } parsed)
				{
					Line($"    Request requirements: {Requirements(parsed.RequestType)}");
					Line($"    Response requirements: {Requirements(parsed.ResponseType)}");
				}

				foreach (var reason in reasons)
					Line($"    Reason: {reason}");

				void CheckConstraints(string name, ConstraintInfo constraints, GenericType actual)
				{
					if (BehaviorMatching.IsValid(constraints, actual))
						return;

					if (constraints.ExactType is { } exact)
						reasons.Add($"{name} type mismatch: required {exact}; actual {actual.Name}.");
					else
					{
						var missing = constraints.TypeConstraints.Where(c => !actual.Implements.Contains(c, StringComparer.Ordinal));
						reasons.Add($"{name} constraints not satisfied: {string.Join(", ", missing)}; actual {actual.Name}; available types: {AvailableTypes(actual)}.");
					}
				}
			}
		}

		context.AddSource("Debug.g.cs", text.ToString());
		return;

		void Line(string value) => text.Append("//").Append(value.Length == 0 ? string.Empty : " ").Append(value).Append('\n');
	}

	private static string AvailableTypes(GenericType type) => type.Implements.Count == 0
		? "(none)"
		: string.Join(", ", type.Implements);

	private static string Requirements(ConstraintInfo constraints) => constraints.ExactType is { } exact
		? $"exact type {exact}"
		: constraints.TypeConstraints.Count == 0
			? "any type (no type constraints)"
			: string.Join(", ", constraints.TypeConstraints);
}
